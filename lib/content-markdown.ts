import fs from "node:fs";
import path from "node:path";
import type { Lesson } from "./content";
import type { SourceCategory } from "./content";

/**
 * Imports authored Markdown lessons from lessons/**\/*.md into the Lesson shape.
 *
 * Design rule: **never fabricate assessment content.** A Markdown lesson
 * contributes its real prose, its real objectives and its own front-matter.
 * Where the author supplied no knowledge check, none is invented: the lesson is
 * marked `kind: "reference"`, carries no auto-scored quiz, and is evidenced by
 * a written defence instead. Guessing "correct" multiple-choice answers on the
 * author's behalf would be exactly the kind of unsupported claim this Academy
 * is meant to prevent.
 *
 * Optional front matter (YAML-ish, `key: value` at the top of the file) may
 * supply: id, moduleId, pillar, status, questions (JSON array), build, defend.
 */

const FRONT_MATTER_KEYS = new Set([
  "id", "moduleId", "pillar", "status", "questions", "build", "defend", "caseStudy", "source",
]);

interface FrontMatter { [key: string]: string }

function splitFrontMatter(raw: string): { meta: FrontMatter; body: string } {
  if (!raw.startsWith("---")) return { meta: {}, body: raw };
  const end = raw.indexOf("\n---", 3);
  if (end < 0) return { meta: {}, body: raw };
  const block = raw.slice(raw.indexOf("\n") + 1, end);
  const meta: FrontMatter = {};
  for (const line of block.split("\n")) {
    const m = /^([A-Za-z0-9_]+):\s*(.*)$/.exec(line.trim());
    if (m && FRONT_MATTER_KEYS.has(m[1])) meta[m[1]] = m[2].trim();
  }
  return { meta, body: raw.slice(end + 4).replace(/^\r?\n/, "") };
}

function stripInline(s: string): string {
  return s.replace(/\*\*/g, "").replace(/`/g, "").replace(/\\([,.;:])/g, "$1").trim();
}

interface Section { heading: string; body: string; level: 2 | 3 }

/** Pull `##` and `###` headings with their content, in document order. */
function parseSections(md: string): Section[] {
  const lines = md.split(/\r?\n/);
  const sections: Section[] = [];
  let current: Section | null = null;
  for (const line of lines) {
    const h3 = /^###\s+(.*)$/.exec(line);
    const h2 = /^##\s+(.*)$/.exec(line);
    if (h2) {
      current = { heading: stripInline(h2[1]), body: "", level: 2 };
      sections.push(current);
    } else if (h3 && current) {
      current = { heading: stripInline(h3[1]), body: "", level: 3 };
      sections.push(current);
    } else if (current) {
      current.body += (current.body ? "\n" : "") + line;
    }
  }
  return sections;
}

function extractBlockquoteField(md: string, label: string): string {
  const re = new RegExp(`^>\\s*\\*\\*${label}:\\*\\*\\s*(.*)$`, "im");
  return stripInline(re.exec(md)?.[1] ?? "");
}

function extractBulletList(section: Section | undefined): string[] {
  if (!section) return [];
  return section.body
    .split(/\r?\n/)
    .map((l) => /^\s*[-*]\s+(.*)$/.exec(l)?.[1])
    .filter((x): x is string => !!x)
    .map(stripInline);
}

function markdownToText(md: string): string {
  return md
    .split(/\r?\n/)
    .map((l) => l
      .replace(/^#{1,6}\s+/, "")
      .replace(/\*\*(.+?)\*\*/g, "$1")
      .replace(/`(.+?)`/g, "$1")
      .replace(/^\s*>\s?/, "")
      .replace(/^\s*[-*]\s+/, "- ")
      .trimEnd())
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

export function parseMarkdownLesson(filePath: string, raw: string): Lesson | null {
  const { meta, body } = splitFrontMatter(raw);
  const titleMatch = /^#\s+(.*)$/m.exec(body);
  if (!titleMatch) return null;
  const title = stripInline(titleMatch[1]);

  const rel = path.relative(process.cwd(), filePath).replace(/\\/g, "/");
  const slug = path.basename(filePath, ".md");
  const id = meta.id || slug;
  const sections = parseSections(body);

  const purpose = extractBlockquoteField(body, "Purpose");
  const caseStudy = meta.caseStudy ?? extractBlockquoteField(body, "Case study");

  const objectivesSection = sections.find((s) => /learning objectives/i.test(s.heading));
  const objectives = extractBulletList(objectivesSection);
  const contentSections = sections.filter(
    (s) => s !== objectivesSection && s.body.trim().length > 0 && !/^(references|further reading|sources)$/i.test(s.heading),
  );

  const questions = meta.questions ? safeParse(meta.questions, [] as unknown[]) : [];

  const sourceCategory: SourceCategory = "Supplementary free learning resource";
  const verification = [
    "Imported from an authored Markdown lesson, not generated by the Academy. Wording is the author's.",
    caseStudy
      ? `Case study states its own limits: ${caseStudy}`
      : "No case study was supplied.",
    questions.length === 0
      ? "No knowledge check was supplied, so none was generated. This lesson is evidenced by written work instead of a quiz."
      : `Knowledge check supplied by the author (${questions.length} questions).`,
  ];

  return {
    id,
    moduleId: meta.moduleId ?? "",
    pillar: (meta.pillar ?? "Tech") as Lesson["pillar"],
    kind: "reference",
    title,
    estimatedMinutes: { learn: 30, build: 120, defend: 25 },
    objectives: objectives.length ? objectives : [purpose || `Work through ${title}.`],
    prerequisites: [],
    unlock: { prerequisites: [] },
    sources: [
      {
        category: sourceCategory,
        title: `${title} (authored lesson)`,
        url: `https://github.com/Crispen-ux/cto-training/blob/main/${rel}`,
        reviewed: new Date().toISOString().slice(0, 10),
        reviewDepth: "Imported verbatim from the authored Markdown source. Not summarised or rewritten.",
      },
    ],
    verificationNotes: verification,
    learn: {
      sections: contentSections.map((s) => ({
        heading: s.heading,
        sourceCategory,
        body: markdownToText(s.body),
      })),
      workedExample: {
        sourceCategory,
        title: caseStudy ? "Case study" : "Source material",
        body: caseStudy || purpose || markdownToText(body).slice(0, 600),
      },
      misconceptions: [],
      explainTask: objectives.length
        ? `Explain, in your own words and without notes: ${objectives.slice(0, 3).join("; ")}.`
        : `Explain ${title} and where it applies in a real system.`,
    },
    knowledgeCheck: questions as Lesson["knowledgeCheck"],
    build: safeParse(meta.build, {
      business: `Apply "${title}" to work you actually do, or to a clearly labelled simulation.`,
      problem: `Produce a worked artefact that demonstrates the objectives above.`,
      requirements: objectives.length ? objectives : ["Produce a written explanation with a concrete example."],
      constraints: [
        "Label clearly what was designed, what was implemented, what was tested and what was verified in practice.",
        "Do not present an estimate as a measurement.",
      ],
      design: "One page: the requirement, the option chosen, the trade-off accepted and the evidence.",
      tasks: ["Apply the material to a real or simulated case.", "Record what evidence exists.", "State what you would do differently."],
      acceptance: ["Evidence is referenced and real.", "Assumptions and estimates are labelled.", "Trade-offs are explained."],
      deliverable: "A written artefact with references, referenced by path or link.",
    }) as Lesson["build"],
    defend: safeParse(meta.defend, {
      assessor: "Principal Engineer",
      scenario: `A colleague challenges your understanding of ${title}.`,
      prompts: objectives.length
        ? objectives.slice(0, 4).map((o) => `Explain and justify: ${o}`)
        : [`Explain ${title} and its trade-offs.`],
      rubric: [
        { criterion: "Technical accuracy of the explanation", weight: 0.3 },
        { criterion: "Use of concrete evidence over assertion", weight: 0.3 },
        { criterion: "Trade-offs and limitations stated honestly", weight: 0.25 },
        { criterion: "Clarity for a senior audience", weight: 0.15 },
      ],
    }) as Lesson["defend"],
  };
}

function safeParse<T>(raw: string | undefined, fallback: T): T {
  if (!raw) return fallback;
  try {
    return JSON.parse(raw) as T;
  } catch {
    return fallback;
  }
}

function walk(dir: string, out: string[] = []): string[] {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name.endsWith(".md")) out.push(full);
  }
  return out;
}

export function loadMarkdownLessons(): Lesson[] {
  const dir = path.join(process.cwd(), "lessons");
  const out: Lesson[] = [];
  for (const file of walk(dir)) {
    try {
      const lesson = parseMarkdownLesson(file, fs.readFileSync(file, "utf8"));
      if (lesson) out.push(lesson);
    } catch {
      // a malformed lesson must not break the whole curriculum
    }
  }
  return out;
}
